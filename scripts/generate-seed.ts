// Generates supabase/seed.sql from src/data/demo.ts so a fresh database starts
// with the same starter content as the local preview. Run: npm run generate:seed
import { writeFileSync } from 'node:fs'
import { demoCollections, demoGallery, demoProducts, demoSettings } from '../src/data/demo.ts'

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'boolean' || typeof v === 'number') return String(v)
  if (Array.isArray(v)) return v.length ? `array[${v.map(q).join(', ')}]::text[]` : `'{}'::text[]`
  return `'${String(v).replace(/'/g, "''")}'`
}
const row = (cols: string[], obj: Record<string, unknown>) => `(${cols.map((c) => q(obj[c])).join(', ')})`
const insert = (table: string, cols: string[], rows: Record<string, unknown>[]) =>
  `insert into public.${table} (${cols.join(', ')}) values\n  ${rows.map((r) => row(cols, r)).join(',\n  ')}\non conflict (id) do nothing;\n`

const out = [
  '-- Starter content for BUSTLAB. Generated by scripts/generate-seed.ts — do not edit by hand.',
  '-- Images reference bundled placeholder renders under /images and can be replaced in the admin.',
  '',
  insert('collections', ['id', 'name', 'slug', 'description', 'cover_image', 'display_order', 'active'], demoCollections),
  insert(
    'products',
    ['id', 'name', 'slug', 'short_description', 'description', 'category_id', 'main_image', 'gallery_images', 'dimensions', 'material_description', 'ready_to_paint', 'featured', 'shopify_url', 'etsy_url', 'published', 'display_order', 'created_at'],
    demoProducts,
  ),
  insert('gallery_images', ['id', 'image_url', 'caption', 'alt_text', 'collection_id', 'is_painted_example', 'display_order', 'published'], demoGallery),
  `update public.site_settings set
  announcement_enabled = ${q(demoSettings.announcement_enabled)},
  announcement_text = ${q(demoSettings.announcement_text)},
  announcement_link = ${q(demoSettings.announcement_link)},
  footer_tagline = ${q(demoSettings.footer_tagline)}
where id = 1 and announcement_text is null;
`,
]
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'))
console.log('Wrote supabase/seed.sql')
